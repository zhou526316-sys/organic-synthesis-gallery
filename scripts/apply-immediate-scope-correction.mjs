import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { CORRECTION_FILES, MARKER_FILE, doiKey, decodeDataset, dropOnly, collectDois } from './lib/immediate-scope-correction.mjs';
import { loadScopeCorrections } from './lib/scope-corrections.mjs';
import { authorize } from './validate-pages-literature-authorization.mjs';
const git = args => execFileSync('git',args,{encoding:'utf8',maxBuffer:64*1024*1024}).trim();
const pretty = x => JSON.stringify(x,null,2)+'\n';
const sha = text => createHash('sha1').update(`blob ${Buffer.byteLength(text)}\0`).update(text).digest('hex');
const requestFile = process.argv[2] || 'audit/automation-triggers/scope-removal-request.json';
const request = JSON.parse(readFileSync(requestFile,'utf8'));
assert.equal(request.schemaVersion,1);
assert.equal(request.mode,'confirmed-scope-removal');
assert.deepEqual(request.addDois,[]);
const state = JSON.parse(readFileSync('audit/literature-update-state.json','utf8'));
assert(!state.activeRun, 'blocked_by_concurrent_change: active literature run');
const prior = JSON.parse(readFileSync(MARKER_FILE,'utf8'));
const previousReleaseCommit = git(['rev-parse','HEAD']);
assert.equal(git(['status','--porcelain','--',...CORRECTION_FILES,MARKER_FILE,'audit/literature-update-state.json']), '', 'Dirty authoritative files');
const authorityFile = 'audit/scope-removal-authority.json';
const authority = JSON.parse(readFileSync(authorityFile,'utf8'));
assert(authority.allowImmediateConfirmedRemoval && authority.allowOffSlotAdmissions === false);
const priorProof = await authorize();
assert(priorProof.ok, 'Previous snapshot is not authorized: '+priorProof.failures.join('; '));
const registry = await loadScopeCorrections();
const byDoi = new Map(registry.map(row => [doiKey(row.doi),row]));
const requested = request.removeDois.map(doiKey);
assert(requested.length && new Set(requested).size === requested.length, 'Invalid requested DOI set');
for(const doi of requested) assert(byDoi.get(doi)?.decision === 'exclude', 'No final exclusion: '+doi);
const datasets = new Map(CORRECTION_FILES.filter(file=>!file.endsWith('.js')).map(file=>[file,decodeDataset(file,readFileSync(file,'utf8'))]));
const before = collectDois([...datasets.values()]);
assert.equal(before.size,prior.productionCards,'Previous card count mismatch');
const removed = requested.filter(doi=>before.has(doi));
assert(removed.length,'Nothing to remove; refuse duplicate mutation');
const replacements = new Map();
for(const [file,value] of datasets) {
  const filtered = dropOnly(file,value,removed);
  if (JSON.stringify(filtered) !== JSON.stringify(value)) replacements.set(file,file.endsWith('.gz.b64') ? gzipSync(Buffer.from(JSON.stringify(filtered))).toString('base64')+'\n' : pretty(filtered));
}
const after = collectDois([...datasets].map(([file,value])=>dropOnly(file,value,removed)));
assert.equal(after.size,before.size-removed.length);
const now = new Date().toISOString();
const id = 'scope-correction-'+now.replace(/[^0-9]/g,'');
const correctionReviewFile = `audit/scope-rechecks/${id}.json`;
const review = {schemaVersion:1,mode:'scope-correction',generatedAt:now,requestFile,source:'explicit_user_confirmed_exclusions',accepted:[],rejected:removed.map(doi=>byDoi.get(doi)),pending:[],summary:{reviewed:removed.length,accepted:0,rejected:removed.length,pending:0},qualityControl:{secondPassCompleted:true,unresolvedDisagreements:0},note:'Only previously confirmed out-of-scope entries are removed. This does not claim a complete new discovery audit or global semantic closure.'};
const reviewText=pretty(review);
const protectedBlobs={...prior.protectedBlobs};
for(const [file,text] of replacements) protectedBlobs[file]=sha(text);
const marker={schemaVersion:3,mode:'scope-correction',releasePolicy:'deletion-only',correctionId:id,correctedAt:now,productionCards:after.size,previousProductionCards:before.size,previousReleaseCommit,previousMarkerBlobSha:git(['rev-parse',`HEAD:${MARKER_FILE}`]),lastFixedPublicationSlot:prior.lastFixedPublicationSlot||prior.publicationSlot||null,protectedBlobs,removedDois:removed,publishableDois:[],deferredDois:prior.deferredDois||[],...(prior.pendingQueueFile?{pendingQueueFile:prior.pendingQueueFile,pendingQueueBlobSha:prior.pendingQueueBlobSha}:{}),correctionReviewFile,correctionReviewBlobSha:sha(reviewText),correctionRegistryFile:'audit/literature-scope-corrections.json',correctionRegistryBlobSha:git(['hash-object','audit/literature-scope-corrections.json']),authorityFile,authorityBlobSha:git(['hash-object',authorityFile]),note:'Immediate confirmed removals only; unchanged papers and pending backlog preserved; new admissions still use 08:00/18:00.'};
// All assertions are complete before creating any production replacement.
for(const [file,text] of replacements) writeFileSync(file,text);
writeFileSync(correctionReviewFile,reviewText);
writeFileSync(MARKER_FILE,pretty(marker));
state.lastScopeCorrection={id,mode:'deletion-only',status:'awaiting_deployment',correctedAt:now,removedDois:removed,beforeCards:before.size,afterCards:after.size,reviewFile:correctionReviewFile,reviewBlobSha:marker.correctionReviewBlobSha};
writeFileSync('audit/literature-update-state.json',pretty(state));
const result={ok:true,id,mode:'deletion-only',correctedAt:now,previousReleaseCommit,removedDois:removed,beforeCards:before.size,afterCards:after.size,reviewFile:correctionReviewFile,files:[...replacements.keys(),correctionReviewFile,MARKER_FILE,'audit/literature-update-state.json','audit/scope-removal-execution-result.json'],deploymentVerified:false,producedNewPapers:0};
writeFileSync('audit/scope-removal-execution-result.json',pretty(result));
console.log(pretty(result));
